#!/usr/bin/env bash
# Write one wrapper module and one .cfg per line of an item's verify/MATRIX.
#
# Usage: bash drill/temporal/gen-cfgs.sh drill/temporal/<NN>-<slug>
#
# MATRIX is tab-separated, one run per line, blank lines and # lines skipped:
#
#     tag <TAB> Rows <TAB> cfg body
#
# The tag names the run. Rows is the TLC value bound to CONSTANT Rows, which
# is which behaviors from the prompt the run explores, or "-" for a module
# with no Rows constant. The body is one or more cfg lines joined by ";". A
# body that names its own SPECIFICATION replaces the default
# "SPECIFICATION Spec" line. A body line "\* MODULE: Name" picks which module
# the wrapper extends, for items that check a lasso table and a system spec
# side by side; the default is the name in verify/MODULE.
#
# Each line becomes <Stem>.tla, a three-line module that EXTENDS the base,
# and <Stem>.cfg beside it. The stem is the tag in CamelCase with "Run" on
# the end, so answer-r3 becomes AnswerR3Run. The suffix keeps one stem from
# being a prefix of another, which matters because harness/drill-gate.sh
# finds a module's recorded rc by searching ANSWER.md for the stem as a
# substring. One module per run is also what lets that gate reproduce every
# number in the elimination table rather than one per item.
#
# A line whose body carries CHECK_DEADLOCK gets a cfg only, named by the tag,
# and no wrapper module. verdict.sh refuses that keyword unless it is also
# given -d, which the gate never passes, so those runs belong to
# verify-item.sh alone. The gate walks modules, not cfgs, so a cfg with no
# module beside it is invisible to it.
set -eu
item="${1:?item directory}"
vdir="$item/verify"
matrix="$vdir/MATRIX"
base_default="$(cat "$vdir/MODULE")"

rm -f "$vdir"/*Run.tla "$vdir"/*Run.cfg

stem_of() {
  local tag="$1" part out=""
  IFS=- read -r -a parts <<<"$tag"
  for part in "${parts[@]}"; do out="${out}${part^}"; done
  printf '%sRun' "$out"
}

emit_cfg() {
  local rows="$1" body="$2" out="$3"
  {
    case "$body" in
      *SPECIFICATION*) ;;
      *) printf 'SPECIFICATION Spec\n' ;;
    esac
    if [ "$rows" != "-" ]; then printf 'CONSTANT Rows = %s\n' "$rows"; fi
    printf '%s\n' "$body" | tr ';' '\n' | grep -v '^\\\* MODULE:' || true
  } > "$out"
}

n=0
while IFS=$'\t' read -r tag rows body; do
  case "$tag" in ''|'#'*) continue ;; esac
  base="$base_default"
  case "$body" in
    *'\* MODULE: '*)
      base="${body#*\\* MODULE: }"
      base="${base%%;*}"
      ;;
  esac
  case "$body" in
    *CHECK_DEADLOCK*)
      emit_cfg "$rows" "$body" "$vdir/$tag.cfg"
      ;;
    *)
      stem="$(stem_of "$tag")"
      emit_cfg "$rows" "$body" "$vdir/$stem.cfg"
      {
        printf -- '---- MODULE %s ----\n' "$stem"
        printf '\\* Generated by drill/temporal/gen-cfgs.sh from verify/MATRIX, line "%s".\n' "$tag"
        printf '\\* One run of the matrix: the cfg beside this file picks the rows and\n'
        printf '\\* the property, and this module only names the spec it runs against.\n'
        printf 'EXTENDS %s\n====\n' "$base"
      } > "$vdir/$stem.tla"
      ;;
  esac
  n=$((n + 1))
done < "$matrix"
echo "$n run(s) written to $vdir"
