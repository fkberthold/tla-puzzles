#!/usr/bin/env bash
# gen-misses.sh: gather the candidate misconception comments for a recall
# construct, so somebody can read them and author recall/MISSES.tsv.
#
# Lineage: bead tla-1sh7.3, epic tla-1sh7.
#
# ===========================================================================
# THIS IS AN AID, NOT THE AUTHORITY. It does not write recall/MISSES.tsv and
# it never will. What it prints is raw: a comment from one drill item, naming
# that item's variables and often its whole situation. A MISS row has to say
# the same thing about the construct with no module and no variable in it,
# and that rewrite is a judgment nothing here can make.
#
# So the verb is "gather", not "generate", and the file it feeds is authored
# by hand. Running this over a construct that already has rows is still worth
# doing, because the corpus holds more mistakes per construct than the table
# has room for and the second pass picks different ones.
#
# WHERE THE CANDIDATES COME FROM. 406 of the 498 modules under
# drill/*/*/verify/ open with a comment naming one wrong move and what it
# does. drill/INVENTORY.md field 8 says which items reach a construct, so the
# construct picks the items and the items pick the modules.
#
# Comments that open with "Generated by" are left out. Those belong to the
# temporal family's config matrix, where one module per matrix row says only
# which spec it runs against, and none of them describes a mistake. Pass
# --all to see them anyway.
#
# ===========================================================================
# USAGE
#
#   scripts/gen-misses.sh                    every construct a rep drills
#   scripts/gen-misses.sh K050 K047          those constructs
#   scripts/gen-misses.sh R107               the construct that rep drills
#   scripts/gen-misses.sh --todo             only reps with no MISS row yet
#   scripts/gen-misses.sh --all K050         keep the generated-runner comments
#
# OPTIONS
#   --reps FILE        rep table      (default: recall/REPS.tsv)
#   --misses FILE      miss table     (default: recall/MISSES.tsv)
#   --inventory FILE   construct rows (default: drill/INVENTORY.md)
#   --drill DIR        drill corpus   (default: drill)
#   --todo             list only the reps that have no MISS row
#   --all              do not drop the "Generated by" runner comments
#   -h, --help         this text
#
# EXIT
#   0  printed something
#   2  usage error
#   3  could not run, so nothing was gathered
#
# The repo root is resolved from ${BASH_SOURCE[0]} rather than written out.
# A literal path here would make a run from a worktree write into the main
# checkout, which is the leak a footprint check cannot see (bead tla-1hf).
set -uo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "${SCRIPT_DIR}/.." && pwd)"
cd "${REPO_ROOT}" || exit 1

REPS="recall/REPS.tsv"
MISSES="recall/MISSES.tsv"
INVENTORY="drill/INVENTORY.md"
DRILL="drill"
TODO=0
KEEP_ALL=0
WANTED=()

usage() { sed -n '30,50p' "${BASH_SOURCE[0]}"; }

die_usage() {
  printf 'gen-misses.sh: %s\n' "$1" >&2
  usage >&2
  exit 2
}

die_cannot_run() {
  printf 'gen-misses.sh: %s\n' "$1" >&2
  exit 3
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --reps)      [ "$#" -ge 2 ] || die_usage "--reps needs a file"; REPS="$2"; shift 2 ;;
    --misses)    [ "$#" -ge 2 ] || die_usage "--misses needs a file"; MISSES="$2"; shift 2 ;;
    --inventory) [ "$#" -ge 2 ] || die_usage "--inventory needs a file"; INVENTORY="$2"; shift 2 ;;
    --drill)     [ "$#" -ge 2 ] || die_usage "--drill needs a directory"; DRILL="$2"; shift 2 ;;
    --todo)      TODO=1; shift ;;
    --all)       KEEP_ALL=1; shift ;;
    -h|--help)   usage; exit 0 ;;
    --)          shift; break ;;
    -*)          die_usage "unknown option: $1" ;;
    *)           WANTED+=("$1"); shift ;;
  esac
done
while [ "$#" -gt 0 ]; do WANTED+=("$1"); shift; done

[ -r "$REPS" ]      || die_cannot_run "no rep table at ${REPS}, so nothing was gathered."
[ -r "$INVENTORY" ] || die_cannot_run "no construct rows at ${INVENTORY}, so nothing was gathered."
[ -d "$DRILL" ]     || die_cannot_run "no drill corpus at ${DRILL}, so nothing was gathered."

# A missing miss table is not an error. On the first run there isn't one yet,
# and the whole point of --todo is to say so.
MISS_IDS=""
if [ -r "$MISSES" ]; then
  MISS_IDS=" $(awk -F'\t' '$1 == "MISS" { print $2 }' "$MISSES" | sort -u | tr '\n' ' ')"
fi

miss_count() {
  awk -F'\t' -v id="$1" '
    $1 == "MISS" && $2 == id { n++ }
    END { printf "%d row%s", n + 0, (n == 1 ? "" : "s") }
  ' "$MISSES" 2>/dev/null || printf '0 rows'
}

# The leading comment of one verify module: everything from line 2 up to the
# first line that is not a comment, with the comment punctuation taken off.
leading_comment() {
  awk '
    NR == 1 { next }
    /^[[:space:]]*(\\\*|\(\*)/ {
      line = $0
      sub(/^[[:space:]]*\\\*[[:space:]]?/, "", line)
      sub(/^[[:space:]]*\(\*[[:space:]]?/, "", line)
      sub(/[[:space:]]*\*\)[[:space:]]*$/, "", line)
      sub(/[[:space:]]+$/, "", line)
      print line
      next
    }
    { exit }
  ' "$1"
}

# Every construct a rep drills, in rep order, so the listing follows the table
# a reader already has open.
all_constructs() {
  awk -F'\t' '$1 == "REP" { if (!seen[$3]++) print $3 }' "$REPS"
}

constructs_for() {
  case "$1" in
    R*) awk -F'\t' -v id="$1" '$1 == "REP" && $2 == id { print $3; exit }' "$REPS" ;;
    *)  printf '%s\n' "$1" ;;
  esac
}

# ---------------------------------------------------------------------------
# --todo: the reps with no row, and nothing else. A short list is the expected
# shape of the answer, since a rep with no row falls through to the model call
# and that is the designed fourth layer rather than a gap.
# ---------------------------------------------------------------------------
if [ "$TODO" = "1" ]; then
  printf '# reps with no MISS row\n'
  n=0
  while IFS= read -r row; do
    rid="$(cut -f2 <<<"$row")"
    kcode="$(cut -f3 <<<"$row")"
    prompt="$(cut -f5 <<<"$row")"
    case "$MISS_IDS" in
      *" ${rid} "*) continue ;;
    esac
    printf '%s\t%s\t%s\n' "$rid" "$kcode" "$prompt"
    n=$((n + 1))
  done < <(awk -F'\t' '$1 == "REP"' "$REPS")
  printf '# %s reps with no row\n' "$n"
  exit 0
fi

if [ "${#WANTED[@]}" -eq 0 ]; then
  mapfile -t WANTED < <(all_constructs)
fi

printed=0
for want in "${WANTED[@]}"; do
  kcode="$(constructs_for "$want")"
  if [ -z "$kcode" ]; then
    printf '## %s is in no REP row of %s\n\n' "$want" "$REPS"
    continue
  fi

  row="$(awk -F'\t' -v k="$kcode" '$1 == "ROW" && $2 == k { print; exit }' "$INVENTORY")"
  if [ -z "$row" ]; then
    printf '## %s is in no ROW of %s\n\n' "$kcode" "$INVENTORY"
    continue
  fi
  kname="$(cut -f4 <<<"$row")"
  items="$(cut -f8 <<<"$row")"

  printf '## %s  %s\n' "$kcode" "$kname"

  while IFS= read -r reprow; do
    rid="$(cut -f2 <<<"$reprow")"
    printf '   %s  [%s]  %s\n' "$rid" "$(miss_count "$rid")" "$(cut -f5 <<<"$reprow")"
  done < <(awk -F'\t' -v k="$kcode" '$1 == "REP" && $3 == k' "$REPS")

  if [ -z "$items" ]; then
    printf '\n   no drill item reaches this construct, so there is nothing to gather.\n\n'
    continue
  fi

  found=0
  for slug in ${items//,/ }; do
    for f in "${DRILL}"/*/"${slug}"/verify/*.tla; do
      [ -e "$f" ] || continue
      body="$(leading_comment "$f")"
      [ -n "$body" ] || continue
      if [ "$KEEP_ALL" = "0" ]; then
        case "$body" in
          'Generated by'*) continue ;;
        esac
      fi
      printf '\n   %s\n' "$f"
      sed -n 's/^/     /p' <<<"$body"
      found=$((found + 1))
    done
  done
  printf '\n   %s candidate comments\n\n' "$found"
  printed=$((printed + 1))
done

[ "$printed" -gt 0 ] || die_cannot_run "no construct matched, so nothing was gathered."
exit 0
